# ---------------------------------------------------------------- formatting
def num(x, d=0) -> str:
    """Thousands-separated number with d decimals; LaTeX-safe minus sign."""
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "--"
    s = f"{x:,.{d}f}"
    return s.replace("-", "$-$")


def pct(x, d=1) -> str:
    return num(100 * x, d)


def sgn(x, d=3) -> str:
    """Signed decimal for coefficients."""
    return num(x, d)


def macro(name: str, value) -> None:
    """Register \\name -> value. Names must be letters only."""
    assert re.fullmatch(r"[A-Za-z]+", name), name
    assert name not in MACROS, f"duplicate macro {name}"
    MACROS[name] = str(value)


def prov(p: str) -> str:
    return PROV.get(p, p.replace("-", " ").title())


def table(name: str, body: str) -> None:
    # adjustbox shrinks a table that would overflow the text width and leaves narrower ones alone
    body = "\\begin{adjustbox}{max width=\\textwidth}\n" + body.strip() + "\n\\end{adjustbox}\n"
    (PAPER / "tables" / f"{name}.tex").write_text(HEADER + body, encoding="utf-8")


def est_se(e, s, d=3) -> str:
    return f"{sgn(e, d)} ({num(s, d)})"


