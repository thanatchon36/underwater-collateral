    bib = (ROOT / "01_literature" / "references.bib").read_text(encoding="utf-8")
    bib = re.sub(r"^\s*note\s*=\s*\{[^\n]*\},?\s*\n", "", bib, flags=re.M)
    bib = bib.replace("@misc{UKPACT_BOT,", "@misc{UKPACT_BOT,\n  year = {n.d.},")
    # keep titles in the case they were verified in (plainnat would lower-case proper nouns)
    bib = re.sub(r"^(\s*title\s*=\s*)\{(?!\{)(.*)\}(,?)\s*$", r"\1{{\2}}\3", bib, flags=re.M)
    # curly quotes before a Thai word stop the Thai font transition from firing; use the TeX commands
    bib = bib.replace("\u201c", "\\textquotedblleft{}").replace("\u201d", "\\textquotedblright{}")
    # Thai has no inter-word spaces and tectonic's ICU has no Thai dictionary, so long Thai titles
    # cannot be broken across lines; mark word boundaries (newmm dictionary) with a zero-width glue
    from pythainlp.tokenize import word_tokenize

    def _segment(m: re.Match) -> str:
        words = [w for w in word_tokenize(m.group(0), engine="newmm") if w]
        return "\\hspace{0pt}".join(words)

    bib = re.sub(r"[\u0E00-\u0E7F]{2,}", _segment, bib)
    # bare URLs inside howpublished/note-like fields: escape underscores that would break TeX
    bib = re.sub(r"(https?://\S*?)(?=[\s;,}])", lambda m: m.group(1).replace("_", "\\_") if "\\_" not in m.group(1) else m.group(1),
                 bib.replace("\\_", "\u0000")).replace("\u0000", "\\_")
    (PAPER / "refs.bib").write_text("% Generated by 04_analysis/src/paper_numbers.py from 01_literature/references.bib "
                                    "(verification notes stripped). Do not edit.\n" + bib, encoding="utf-8")

    lines = [HEADER] + [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(MACROS.items())]
    (PAPER / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(MACROS)} macros, {len(list((PAPER / 'tables').glob('*.tex')))} tables")


