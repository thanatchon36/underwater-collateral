def load_env(path=ROOT / ".env"):
    if path.exists():
        for line in path.read_text().splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                os.environ.setdefault(k.strip(), v.strip().strip('"').strip("'"))


def card():
    h = pd.read_csv(HASHES)
    rows = "\n".join(f"| `{Path(r.file).name}` | {int(r.rows):,} | `{r.sha256_decompressed}` |" for r in h.itertuples())
    table = "| File | Rows | SHA-256 of the decompressed CSV |\n|---|---|---|\n" + rows
    return CARD.format(github=GITHUB, zenodo=ZENODO, hashes=table)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default="thanatchon36/underwater-collateral-data")
    ap.add_argument("--dry-run", action="store_true", help="write the dataset card locally and list what would be uploaded")
    a = ap.parse_args()
    load_env()
    out = ROOT / "03_data/hf_dataset_card.md"
    out.write_text(card(), encoding="utf-8")
    print("dataset card written to", out.relative_to(ROOT))
    plan = [(PROCESSED, "processed"), (SYNTHETIC, "synthetic")]
    for src, dst in plan:
        n = sum(1 for p in src.rglob("*") if p.is_file())
        mb = sum(p.stat().st_size for p in src.rglob("*") if p.is_file()) / 1e6
        print(f"{src.relative_to(ROOT)} -> {dst}: {n} files, {mb:.0f} MB")
    if a.dry_run:
        return
    from huggingface_hub import HfApi
    api = HfApi(token=os.environ.get("HF_TOKEN"))  # .env, else the token saved by `huggingface-cli login`
    try:
        print("logged in as", api.whoami()["name"])
    except Exception as e:  # noqa: BLE001
        sys.exit(f"no Hugging Face credentials: put HF_TOKEN in .env or run huggingface-cli login ({type(e).__name__})")
    url = api.create_repo(a.repo, repo_type="dataset", private=False, exist_ok=True)
    print("repo", url)
    api.upload_file(path_or_fileobj=str(out), path_in_repo="README.md", repo_id=a.repo, repo_type="dataset",
                    commit_message="Dataset card")
    api.upload_file(path_or_fileobj=str(HASHES), path_in_repo="registration_hashes.csv", repo_id=a.repo,
                    repo_type="dataset", commit_message="Registration hashes")
    for src, dst in plan:
        api.upload_folder(folder_path=str(src), path_in_repo=dst, repo_id=a.repo, repo_type="dataset",
                          commit_message=f"Tier 1: {dst}", ignore_patterns=[".gitkeep", "*.pyc"])
        print("uploaded", dst)
    print("done:", f"https://huggingface.co/datasets/{a.repo}")


if __name__ == "__main__":
    main()
