"""Upload the project's derived data to a Hugging Face dataset repository.

Tier 1 (default): 03_data/processed/ (the registered sample files and every derived table and raster the
scripts build from the public raw data), 03_data/synthetic/ (seeded synthetic loan panel) and the registration
hash table, with a dataset card that states the provenance and licence of each folder. Raw downloads are not
uploaded by this tier; 03_data/README.md logs where they come from and the download scripts rebuild them.

Credentials: HF_TOKEN in .env (gitignored), never in the code or in git.

Run   : .venv/bin/python -I 04_analysis/src/upload_hf_data.py [--repo thanatchon36/underwater-collateral-data] [--dry-run]
"""

import argparse
import os
import sys
from pathlib import Path

